@Composable
fun RoleBadgePill(role: UserRole, modifier: Modifier = Modifier) {
    val containerColor = when (role) {
        UserRole.ADMIN -> MaterialTheme.colorScheme.secondaryContainer
        UserRole.TEACHER -> MaterialTheme.colorScheme.primaryContainer
        UserRole.PARENT -> MaterialTheme.colorScheme.tertiaryContainer
        UserRole.STUDENT -> MaterialTheme.colorScheme.surfaceVariant
    }
    val contentColor = when (role) {
        UserRole.ADMIN -> MaterialTheme.colorScheme.onSecondaryContainer
        UserRole.TEACHER -> MaterialTheme.colorScheme.onPrimaryContainer
        UserRole.PARENT -> MaterialTheme.colorScheme.onTertiaryContainer
        UserRole.STUDENT -> MaterialTheme.colorScheme.onSurfaceVariant
    }
    Surface(
        modifier = modifier,
        shape = MaterialTheme.shapes.extraLarge,
        color = containerColor
    ) {
        Text(
            text = "${role.labelOromo} • ${role.labelEnglish}",
            style = MaterialTheme.typography.labelMedium,
            fontWeight = FontWeight.SemiBold,
            color = contentColor,
            modifier = Modifier.padding(horizontal = 12.dp, vertical = 5.dp),
            maxLines = 1,
            overflow = TextOverflow.Ellipsis
        )
    }
}

@Composable
fun MetricStatCard(
    title: String,
    value: String,
    subtitle: String,
    icon: ImageVector,
    accentColor: Color = MaterialTheme.colorScheme.primary,
    modifier: Modifier = Modifier
) {
    Card(
        modifier = modifier,
        shape = MaterialTheme.shapes.medium,
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        elevation = CardDefaults.cardElevation(defaultElevation = 2.dp)
    ) {
        Column(modifier = Modifier.padding(14.dp)) {
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween,
                modifier = Modifier.fillMaxWidth()
            ) {
                Box(
                    modifier = Modifier
                        .size(36.dp)
                        .clip(MaterialTheme.shapes.small)
                        .background(accentColor.copy(alpha = 0.14f)),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = icon,
                        contentDescription = title,
                        tint = accentColor,
                        modifier = Modifier.size(20.dp)
                    )
                }
                Text(
                    text = value,
                    style = MaterialTheme.typography.headlineSmall,
                    color = accentColor,
                    fontWeight = FontWeight.Bold
